import * as T from '@tabler/icons-react';
import type { ComponentType, SVGProps } from 'react';

export type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref' | 'stroke'> & { size?: number | string; strokeWidth?: number | string };
export type AppIcon = ComponentType<IconProps>;
/** Eski adıyla uyumluluk */
export type LucideIcon = AppIcon;

function wrap(Comp: T.Icon, name: string): AppIcon {
  const C = ({ strokeWidth, ...rest }: IconProps) => <Comp stroke={strokeWidth ?? 2} {...(rest as object)} />;
  C.displayName = name;
  return C;
}

